/**
 * Сила арены.
 *
 * Арена и раньше была стихийной: у огненного противника — зарево и обломки,
 * у водного — мост и пагода. Но это была декорация, на бой она не влияла.
 *
 * Теперь перед каждым раундом одна стихия проступает в арене и держится
 * весь раунд: узор, собранный на ней, платит вдвое. Бросок случайный, но
 * объявляется до того, как игрок ставит первый ход, — то есть это не
 * «повезло по итогам», а условие задачи. Решение остаётся за игроком:
 * гнаться за силой арены значит повторяться, а повторы противник читает и
 * наказывает. Ровно то натяжение, ради которого всё и затевалось: рандом
 * задаёт вопрос, тактика на него отвечает.
 *
 * Двойная плата, а не лишний урон плашмя: так усиливается решение, которое
 * игрок уже принимает, а не добавляется отдельная мелкая награда сбоку.
 */

import { ELEMENT, ELEMENTS } from './rules.js';

/** Какая стихия сегодня в силе. Бросок один на раунд. */
export function rollFavour(rng) {
    return ELEMENTS[Math.floor(rng() * ELEMENTS.length) % ELEMENTS.length];
}

/** Платит ли этот узор вдвое на этой арене. */
export function isFavoured(combo, favour) {
    return Boolean(combo && favour && combo.element === favour);
}

/** Короткая строка для полосы над ареной. */
export function favourText(favour) {
    if (!favour) return '';
    const el = ELEMENT[favour];
    return `${el.glyph} АРЕНА В СИЛЕ: ${el.name.toUpperCase()} — узор на ней платит вдвое`;
}
